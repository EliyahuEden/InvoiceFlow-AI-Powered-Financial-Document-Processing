"""Hebrew text utilities: visual→logical reordering and script detection.

Many Hebrew PDFs (including most generated by tools without a shaping engine) store
glyphs in *visual* order: the content stream draws characters left-to-right exactly as
they appear on screen. Naive extraction therefore yields reversed Hebrew words
("םולש" instead of "שלום") while digits stay in order. We rebuild each visual line
(left-to-right by x coordinate) and run the Unicode Bidirectional Algorithm with an
RTL base direction, which restores logical order for Hebrew runs while preserving
embedded LTR runs (numbers, Latin product codes, e-mail addresses).
"""
from __future__ import annotations

import re
import unicodedata

from bidi import get_display

HEB_RE = re.compile("[\u0590-\u05FF]")
LATIN_RE = re.compile(r"[A-Za-z]")
NIQQUD_RE = re.compile("[\u0591-\u05C7]")


def has_hebrew(text: str) -> bool:
    return bool(HEB_RE.search(text))


def visual_to_logical(visual_line: str, base_dir: str = "R") -> str:
    """Convert a visual-order line (as drawn left→right) to logical order.

    ``base_dir`` is the paragraph direction: "R" for Hebrew-dominant lines, "L" for
    English lines that merely contain a Hebrew phrase.
    """
    if not has_hebrew(visual_line):
        return visual_line
    out = get_display(visual_line, base_dir=base_dir)
    # Paired brackets are drawn mirrored in RTL text; python-bidi does not mirror them,
    # so we undo the mirroring for RTL paragraphs (rule L4 of the bidi algorithm).
    return out.translate(MIRROR) if base_dir == "R" else out


MIRROR = str.maketrans("()[]{}<>", ")(][}{><")


def script_counts(text: str) -> tuple[int, int]:
    return len(HEB_RE.findall(text)), len(LATIN_RE.findall(text))


def line_direction(text: str, page_dir: str) -> str:
    """Paragraph direction for one line: strong majority wins, otherwise the page direction."""
    heb, lat = script_counts(text)
    if heb + lat == 0:
        return page_dir
    ratio = heb / (heb + lat)
    if ratio >= 0.8:
        return "R"
    if ratio <= 0.2:
        return "L"
    return page_dir


def segment_direction(visual: str, page_dir: str) -> str:
    """Infer the paragraph direction of a visual-order segment.

    Under the Unicode default (first strong character decides), an RTL paragraph has
    its first logical letter - a Hebrew one - at the *right* edge, and an LTR paragraph
    has a Latin letter at the *left* edge. Ambiguous cases fall back to the line's
    script majority and then to the page direction.
    """
    strong = [c for c in visual if HEB_RE.match(c) or LATIN_RE.match(c)]
    if not strong or not has_hebrew(visual):
        return "L"
    left_heb, right_heb = bool(HEB_RE.match(strong[0])), bool(HEB_RE.match(strong[-1]))
    if left_heb and right_heb:
        return "R"
    if not left_heb and not right_heb:
        return "L"
    return line_direction(visual, page_dir)


def detect_language(text: str) -> str | None:
    heb = len(HEB_RE.findall(text))
    lat = len(LATIN_RE.findall(text))
    total = heb + lat
    if total == 0:
        return None
    ratio = heb / total
    if ratio > 0.7:
        return "he"
    if ratio < 0.15:
        return "en"
    return "mixed"


def strip_niqqud(text: str) -> str:
    return NIQQUD_RE.sub("", text)


def clean_text(text: str) -> str:
    """NFKC + remove bidi control marks + normalize Hebrew punctuation variants."""
    text = unicodedata.normalize("NFKC", text)
    text = re.sub(r"[‎‏‪-‮⁦-⁩]", "", text)
    return text.replace("״", '"').replace("׳", "'").replace("–", "-").replace("—", "-")
