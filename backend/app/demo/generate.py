"""Generate the synthetic demo documents into data/demo (committed to the repository).

    python -m app.cli generate-docs
"""
from __future__ import annotations

import json
from pathlib import Path

from app.core.config import REPO_ROOT
from app.demo import render
from app.demo.knowledge import KNOWLEDGE
from app.demo.spec import INVOICES, SUPPLIERS_BY_KEY, UPLOAD_SAMPLES, InvoiceSpec

DATA_DIR = REPO_ROOT / "data" / "demo"


def invoice_truth(inv: InvoiceSpec) -> dict:
    """Ground-truth labels for an invoice, derived from its structured specification."""
    sup = SUPPLIERS_BY_KEY[inv.supplier]
    return {
        "supplier_key": inv.supplier,
        "supplier_name": inv.supplier_display_name or (sup.name if inv.template.startswith("he") else sup.name_en),
        "supplier_tax_id": sup.tax_id if inv.show_tax_id else None,
        "invoice_number": inv.number,
        "invoice_date": inv.invoice_date.isoformat(),
        "currency": inv.currency if (inv.template != "he_compact") else None,  # he_compact prints no currency
        "po_reference": inv.po_reference,
        "payment_terms": inv.payment_terms,
        "subtotal": str(inv.subtotal),
        "tax_rate": str(inv.vat_rate),
        "tax_amount": str(inv.vat),
        "total": str(inv.total),
        "allocation_number": inv.allocation_number,
        "lines": [{"sku": ln.sku, "description": ln.description, "quantity": str(ln.quantity),
                   "unit_price": str(ln.unit_price), "line_total": str(ln.total)} for ln in inv.lines],
    }


def generate(out_dir: Path = DATA_DIR) -> dict:
    manifest: dict = {"provenance": "Synthetic documents generated by backend/app/demo/generate.py from "
                                    "backend/app/demo/spec.py and knowledge.py. All entities are fictional.",
                      "invoices": [], "upload_samples": [], "knowledge": []}
    for group, specs, folder in (("invoices", INVOICES, "invoices"), ("upload_samples", UPLOAD_SAMPLES, "upload_samples")):
        for inv in specs:
            data, ext = render.render_invoice(inv)
            path = out_dir / folder / f"{inv.key}{ext}"
            render.write(path, data)
            manifest[group].append({
                "file": f"{folder}/{path.name}", "scenario": inv.scenario, "template": inv.template, "render": inv.render,
                "language": "mixed" if SUPPLIERS_BY_KEY[inv.supplier].lang == "mixed"
                else ("he" if inv.template.startswith("he") else "en"),
                "expected_findings": inv.expected_findings, "description": inv.description, "truth": invoice_truth(inv)})
    for k in KNOWLEDGE:
        data = render.render_text_document(k.title, k.blocks, rtl=k.language != "en", meta=k.meta)
        path = out_dir / "knowledge" / f"{k.key}.pdf"
        render.write(path, data)
        manifest["knowledge"].append({"file": f"knowledge/{path.name}", "key": k.key, "title": k.title,
                                      "doc_type": k.doc_type, "supplier": k.supplier, "language": k.language,
                                      "effective_date": k.effective_date.isoformat(), "version": k.version})
    (out_dir / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    return manifest
